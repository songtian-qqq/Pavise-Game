using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;

namespace PaviseApp
{
	// Builds the mihomo/sing-box-compatible config that the bundled core runs.
	// Two shapes exist: a probe config (no TUN, just the outbound list) and a
	// route config (TUN on, only the game's process is sent to the proxy).
	internal static class NetRouteConfig
	{
		internal const string GameGroup = "GAME";

		internal const string TestUrl = "http://www.gstatic.com/generate_204";

		internal static string Quote(string value)
		{
			string text = (value ?? "").Replace("\\", "\\\\").Replace("\"", "\\\"");
			return "\"" + text + "\"";
		}

		private static void Line(StringBuilder builder, string text)
		{
			builder.Append(text).Append('\n');
		}

		internal static string NodeLines(NetNode node)
		{
			StringBuilder stringBuilder = new StringBuilder();
			stringBuilder.Append("  - {name: ").Append(Quote(node.Tag)).Append(", type: ").Append(Quote(node.Type));
			stringBuilder.Append(", server: ").Append(Quote(node.Server));
			stringBuilder.Append(", port: ").Append(node.Port.ToString(CultureInfo.InvariantCulture));
			switch (node.Type)
			{
			case "ss":
				stringBuilder.Append(", cipher: ").Append(Quote(string.IsNullOrEmpty(node.Cipher) ? "aes-256-gcm" : node.Cipher));
				stringBuilder.Append(", password: ").Append(Quote(node.Password));
				stringBuilder.Append(", udp: true");
				break;
			case "vmess":
				stringBuilder.Append(", uuid: ").Append(Quote(node.Uuid));
				stringBuilder.Append(", alterId: ").Append(Math.Max(0, node.AlterId).ToString(CultureInfo.InvariantCulture));
				stringBuilder.Append(", cipher: ").Append(Quote(string.IsNullOrEmpty(node.Cipher) ? "auto" : node.Cipher));
				stringBuilder.Append(", udp: true");
				break;
			case "vless":
				stringBuilder.Append(", uuid: ").Append(Quote(node.Uuid));
				if (!string.IsNullOrEmpty(node.Flow))
				{
					stringBuilder.Append(", flow: ").Append(Quote(node.Flow));
				}
				break;
			case "trojan":
				stringBuilder.Append(", password: ").Append(Quote(node.Password));
				stringBuilder.Append(", udp: true");
				break;
			case "hysteria2":
				stringBuilder.Append(", password: ").Append(Quote(node.Password));
				if (!string.IsNullOrEmpty(node.Obfs))
				{
					stringBuilder.Append(", obfs: ").Append(Quote(node.Obfs));
					if (!string.IsNullOrEmpty(node.ObfsPassword))
					{
						stringBuilder.Append(", obfs-password: ").Append(Quote(node.ObfsPassword));
					}
				}
				break;
			case "socks5":
			case "http":
				if (!string.IsNullOrEmpty(node.Username))
				{
					stringBuilder.Append(", username: ").Append(Quote(node.Username));
				}
				if (!string.IsNullOrEmpty(node.Password))
				{
					stringBuilder.Append(", password: ").Append(Quote(node.Password));
				}
				if (node.Tls)
				{
					stringBuilder.Append(", tls: true");
				}
				break;
			}
			if (node.Tls && (node.Type == "vmess" || node.Type == "vless" || node.Type == "trojan"))
			{
				stringBuilder.Append(", tls: true");
				string text = string.IsNullOrEmpty(node.Sni) ? node.Server : node.Sni;
				stringBuilder.Append(", servername: ").Append(Quote(text));
				if (!string.IsNullOrEmpty(node.Alpn))
				{
					stringBuilder.Append(", alpn: [").Append(Quote(node.Alpn)).Append("]");
				}
			}
			if (!string.IsNullOrEmpty(node.PublicKey) && (node.Type == "vless"))
			{
				stringBuilder.Append(", reality-opts: {public-key: ").Append(Quote(node.PublicKey));
				if (!string.IsNullOrEmpty(node.ShortId))
				{
					stringBuilder.Append(", short-id: ").Append(Quote(node.ShortId));
				}
				stringBuilder.Append('}');
			}
			if (node.SkipCertVerify)
			{
				stringBuilder.Append(", skip-cert-verify: true");
			}
			string network = node.Network ?? "";
			if (network.Length > 0 && network != "tcp")
			{
				stringBuilder.Append(", network: ").Append(Quote(network));
				if (network == "ws")
				{
					stringBuilder.Append(", ws-opts: {path: ").Append(Quote(string.IsNullOrEmpty(node.Path) ? "/" : node.Path));
					if (!string.IsNullOrEmpty(node.HostHeader))
					{
						stringBuilder.Append(", headers: {Host: ").Append(Quote(node.HostHeader)).Append('}');
					}
					stringBuilder.Append('}');
				}
				else if (network == "grpc")
				{
					stringBuilder.Append(", grpc-opts: {grpc-service-name: ").Append(Quote(node.Path ?? "")).Append('}');
				}
			}
			stringBuilder.Append("}\n");
			return stringBuilder.ToString();
		}

		internal static string Build(bool routeMode, int mixedPort, int controllerPort, string secret, List<NetNode> nodes, string gameExePath)
		{
			StringBuilder stringBuilder = new StringBuilder();
			Line(stringBuilder, "# Generated by Pavise for a single session. Do not edit.");
			Line(stringBuilder, "mixed-port: " + mixedPort.ToString(CultureInfo.InvariantCulture));
			Line(stringBuilder, "allow-lan: false");
			Line(stringBuilder, "bind-address: 127.0.0.1");
			Line(stringBuilder, "mode: rule");
			Line(stringBuilder, "log-level: warning");
			Line(stringBuilder, "ipv6: false");
			Line(stringBuilder, "unified-delay: true");
			Line(stringBuilder, "tcp-concurrent: true");
			Line(stringBuilder, "find-process-mode: always");
			Line(stringBuilder, "external-controller: 127.0.0.1:" + controllerPort.ToString(CultureInfo.InvariantCulture));
			Line(stringBuilder, "secret: " + Quote(secret));
			Line(stringBuilder, "profile: {store-selected: false, store-fake-ip: false}");
			if (routeMode)
			{
				Line(stringBuilder, "dns:");
				Line(stringBuilder, "  enable: true");
				Line(stringBuilder, "  ipv6: false");
				Line(stringBuilder, "  enhanced-mode: fake-ip");
				Line(stringBuilder, "  fake-ip-range: 198.18.0.1/16");
				Line(stringBuilder, "  default-nameserver: [223.5.5.5, 119.29.29.29]");
				Line(stringBuilder, "  nameserver: [223.5.5.5, 119.29.29.29]");
				Line(stringBuilder, "  fallback: [tls://dns.alidns.com:853]");
				Line(stringBuilder, "  fallback-filter: {geoip: false}");
				Line(stringBuilder, "tun:");
				Line(stringBuilder, "  enable: true");
				Line(stringBuilder, "  stack: system");
				Line(stringBuilder, "  auto-route: true");
				Line(stringBuilder, "  auto-detect-interface: true");
				Line(stringBuilder, "  dns-hijack: [any:53]");
				Line(stringBuilder, "  strict-route: false");
			}
			Line(stringBuilder, "proxies:");
			foreach (NetNode node in nodes)
			{
				stringBuilder.Append(NodeLines(node));
			}
			Line(stringBuilder, "proxy-groups:");
			stringBuilder.Append("  - {name: ").Append(Quote(GameGroup)).Append(", type: select, proxies: [");
			for (int i = 0; i < nodes.Count; i++)
			{
				if (i > 0)
				{
					stringBuilder.Append(", ");
				}
				stringBuilder.Append(Quote(nodes[i].Tag));
			}
			stringBuilder.Append("]}\n");
			Line(stringBuilder, "rules:");
			if (routeMode)
			{
				Line(stringBuilder, "  - PROCESS-NAME,explorer.exe,DIRECT");
				Line(stringBuilder, "  - PROCESS-NAME,Pavise.exe,DIRECT");
				Line(stringBuilder, "  - PROCESS-NAME,mihomo.exe,DIRECT");
				Line(stringBuilder, "  - PROCESS-NAME,clash-meta.exe,DIRECT");
				string text = SafeExeName(gameExePath);
				if (!string.IsNullOrEmpty(text))
				{
					Line(stringBuilder, "  - PROCESS-NAME," + text + "," + GameGroup);
				}
				Line(stringBuilder, "  - MATCH,DIRECT");
			}
			else
			{
				Line(stringBuilder, "  - MATCH,DIRECT");
			}
			return stringBuilder.ToString();
		}

		internal static string SafeExeName(string path)
		{
			if (string.IsNullOrEmpty(path))
			{
				return "";
			}
			try
			{
				string fileName = System.IO.Path.GetFileName(path);
				if (fileName.Length == 0 || fileName.IndexOfAny(new char[3] { ',', '\r', '\n' }) >= 0)
				{
					return "";
				}
				return fileName;
			}
			catch
			{
				return "";
			}
		}

		internal static bool WriteConfig(string path, string content, out string error)
		{
			error = "";
			try
			{
				string[] array = content.Replace("\r", "").Split(new char[1] { '\n' }, StringSplitOptions.None);
				if (!AtomicFile.WriteLines(path, array, "netroute-config"))
				{
					error = "config write failed";
					return false;
				}
				return true;
			}
			catch (Exception ex)
			{
				error = ex.GetType().Name + ": " + ex.Message;
				return false;
			}
		}
	}
}
